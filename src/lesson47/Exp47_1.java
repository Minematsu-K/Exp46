package lesson47;

public class Exp47_1 {
	public static void main(String[] args) {
		System.out.println(Math.abs(-10)); //絶対値 	10
		System.out.println(Math.max(10, 20)); //大きい方	20 
		System.out.println(Math.min(10, 20)); //小さい方 10
		System.out.println(Math.pow(2, 3)); //べき乗値（○の△乗）8(2^3) 
		System.out.println(Math.sqrt(16)); //平方根	4
		System.out.println(Math.round(3.6)); //四捨五入	4
		System.out.println(Math.ceil(3.6)); //切り上げ 	4
		System.out.println(Math.floor(3.6)); //切り捨て 	3
		System.out.println(Math.PI); //円周率 			3.1415...
	}
}